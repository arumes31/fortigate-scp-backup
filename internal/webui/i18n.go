package webui

import "fmt"

// Localize translates stable, server-owned page copy. English phrases are the
// catalog keys so extension templates can share the helper without importing
// the host web package. Unknown copy and languages fall back to English.
func Localize(lang, english string, args ...any) string {
	text := english
	if lang == "de" {
		if translated, ok := germanPageText[english]; ok {
			text = translated
		}
	}
	if len(args) > 0 {
		return fmt.Sprintf(text, args...)
	}
	return text
}

